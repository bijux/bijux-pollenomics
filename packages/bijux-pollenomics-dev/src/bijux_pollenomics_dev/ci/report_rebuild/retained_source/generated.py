"""Serialize captured VCS version metadata without importing or executing source."""

from __future__ import annotations

import hashlib
from typing import Any

from .objects import MAX_MEMBER_BYTES, require

PROVIDER = "vcs-versioning.default-python"
GENERATOR_SHA256 = "dd7ded849d3bacc8e13b0b675ed991904eb896fc79b4607f4f70ee32e47171d9"
GENERATOR_BYTES = 4479


def serialize(version: str, values: tuple[int | str, ...]) -> bytes:
    """Serialize the supported standard metadata statement layout, not its original genesis."""
    exports = (
        "__version__",
        "__version_tuple__",
        "version",
        "version_tuple",
        "__commit_id__",
        "commit_id",
    )
    lines = [
        "# file generated by vcs-versioning",
        "# don't change, don't track in version control",
        "from __future__ import annotations",
        "",
        "__all__ = [",
    ]
    lines.extend(f'    "{name}",' for name in exports)
    lines.extend(
        [
            "]",
            "",
            "version: str",
            "__version__: str",
            "__version_tuple__: tuple[int | str, ...]",
            "version_tuple: tuple[int | str, ...]",
            "commit_id: str | None",
            "__commit_id__: str | None",
            "",
            f"__version__ = version = {version!r}",
            f"__version_tuple__ = version_tuple = {values!r}",
            "",
            "__commit_id__ = commit_id = None",
            "",
        ]
    )
    return "\n".join(lines).encode("utf-8")


def reconstruct(row: dict[str, Any], identity: dict[str, Any]) -> bytes:
    """Check byte correspondence; neither generator execution nor version derivation is recovered."""
    generator = row["generator"]
    require(
        type(generator) is dict and set(generator) == {"provider", "sha256", "bytes"},
        "explicit standard serializer correspondence required",
    )
    require(
        generator["provider"] == PROVIDER
        and generator["sha256"] == GENERATOR_SHA256
        and type(generator["bytes"]) is int
        and generator["bytes"] == GENERATOR_BYTES,
        "unsupported standard generator correspondence",
    )
    require(
        row["original_generator_execution_claimed"] is False
        and row["original_version_derivation_claimed"] is False,
        "generated content correspondence is not original genesis",
    )
    scalars = row["scalars"]
    require(
        type(scalars) is dict
        and set(scalars) == {"version", "version_tuple", "short_node"},
        "exact generated scalar schema required",
    )
    version, values = scalars["version"], scalars["version_tuple"]
    require(
        type(version) is str
        and 0 < len(version) <= 128
        and not any(ord(c) < 32 for c in version),
        "literal version metadata required",
    )
    require(
        type(values) is list
        and 0 < len(values) <= 16
        and all(
            type(item) is int
            and item >= 0
            or type(item) is str
            and 0 < len(item) <= 64
            and not any(ord(c) < 32 for c in item)
            for item in values
        ),
        "typed version tuple required",
    )
    require(
        scalars["short_node"] is None,
        "only the reviewed null-node serialization is supported",
    )
    output = serialize(version, tuple(values))
    require(
        type(identity["bytes"]) is int
        and 0 <= identity["bytes"] <= MAX_MEMBER_BYTES
        and len(output) == identity["bytes"]
        and hashlib.sha256(output).hexdigest() == identity["sha256"],
        "generated metadata differs from original logical source identity",
    )
    return output
