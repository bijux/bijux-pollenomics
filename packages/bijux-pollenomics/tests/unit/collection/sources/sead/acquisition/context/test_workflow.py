@pytest.mark.parametrize("exact", [True, False])
def test_native_416_eof_requires_exact_next_offset_and_closes_stream(exact):
    from email.message import Message
    from urllib.error import HTTPError

    from bijux_pollenomics.collection.sources.sead.acquisition.full import (
        SeadAcquisitionError,
    )

    source = Source()
    streams = []

    def opener(url, **kwargs):
        if urlsplit(url).path.endswith("/tbl_sites") and kwargs["headers"][
            "Range"
        ].startswith("2-"):
            headers = Message()
            headers["Content-Range"] = "*/2" if exact else "*/1"
            stream = io.BytesIO(b"generated unconsumed error body")
            streams.append(stream)
            raise HTTPError(url, 416, "generated range", headers, stream)
        return source(url, **kwargs)

    collector = collect(opener)
    if exact:
        collector.acquire()
        assert (
            collector.receipts["tbl_sites"]["query_receipts"][0]["pagination"]["pages"][
                -1
            ]["eof"]["kind"]
            == "unsatisfied_range"
        )
    else:
        with pytest.raises(SeadAcquisitionError):
            collector.acquire()
        assert collector.complete is False
    assert streams and all(stream.closed for stream in streams)
