UUID = "c3e38c42-36ad-40dd-8958-436ad141d108"
SITES = (
    SeadContextSite(2, UUID, "review"),
    SeadContextSite(3441, "12ae88cc-a58f-4093-8afd-8cbdf1d95795", "unassigned"),
)


def workflow():
    try:
        return importlib.import_module(
            "bijux_pollenomics.collection.sources.sead.acquisition.context.workflow"
        )
    except ModuleNotFoundError:
        pytest.fail("Unresolved-context dependency workflow is not implemented")


def row(site):
    result = dict.fromkeys(_SITE_PROJECTION.split(","))
    result.update(site_id=site.site_id, site_uuid=site.site_uuid)
    return result


class Page(io.BytesIO):
    """One generated byte response with a literal requested URL."""

    status = 200

    def __init__(self, url, rows):
        super().__init__(json.dumps(rows, allow_nan=False).encode())
        self.url = url


class Source:
    """Generated dependency source; actual requests never occur."""

    def __init__(self, site_rows=None, groups=None):
        self.sites = [row(site) for site in SITES] if site_rows is None else site_rows
        self.groups = [] if groups is None else groups
        self.calls = []

    def __call__(self, url, **kwargs):
        self.calls.append((url, kwargs))
        table = urlsplit(url).path.rsplit("/", 1)[-1]
        offset = int(kwargs["headers"]["Range"].split("-")[0])
        rows = {"tbl_sites": self.sites, "tbl_sample_groups": self.groups}.get(
            table, []
        )
        size = int(kwargs["headers"]["Range"].split("-")[1]) + 1 - offset
        return Page(url, rows[offset : offset + size])


def collect(source, sites=SITES, **limits):
    return workflow().ContextCollector(
        sites=sites,
        run_id="generated-context",
        parent_run_id="generated-parent",
        build_id="generated-build",
        opener=source,
        limits=SeadContextLimits(**limits),
    )


def test_both_unresolved_sites_retained_with_no_assigned_country():
    source = Source()
    collector = collect(source)
    manifest = collector.acquire()
    assert manifest["status"] == "complete_context_only"
    assert manifest["country_admission"] is False
    assert manifest["ecological_event_admission"] is False
    assert manifest["legacy_country_scope_meaning"] == "regional_request_intent_only"
    assert manifest["sites"] == [
        {
            "site_id": s.site_id,
            "site_uuid": s.site_uuid,
            "membership_status": s.membership_status,
        }
        for s in SITES
    ]
    assert len(manifest["tables"]) == 19
    assert len(source.calls) == 4
    assert len(manifest["unexpanded_native_references"]) == 4
    assert json.loads(collector.files()["payloads/tbl_sites.json"])["rows"] == [
        row(site) for site in SITES
    ]
    assert (
        json.loads(collector.files()["receipts/tbl_physical_samples.json"])[
            "completion_basis"
        ]
        == "empty_dependency_identity_set"
    )


@pytest.mark.parametrize(
    "mutation",
    ["uuid", "missing", "extra", "duplicate", "missing-field", "extra-field"],
)
def test_seed_identity_or_projection_failure_stops_before_relation_request(mutation):
    rows = [row(site) for site in SITES]
    if mutation == "uuid":
        rows[0]["site_uuid"] = SITES[1].site_uuid
    if mutation == "missing":
        rows.pop()
    if mutation == "extra":
        rows.append({**row(SITES[0]), "site_id": 999})
    if mutation == "duplicate":
        rows.append(dict(rows[0]))
    if mutation == "missing-field":
        del rows[0]["site_description"]
    if mutation == "extra-field":
        rows[0]["unrequested_value"] = 23
    source = Source(rows)
    collector = collect(source)
    with pytest.raises(ValueError):
        collector.acquire()
    assert all(urlsplit(url).path.endswith("/tbl_sites") for url, _ in source.calls)
    assert any(name.startswith("responses/") for name in collector.files())


def test_foreign_owner_refuses_before_second_relation_page():
    source = Source(
        groups=[{"sample_group_id": 10, "site_id": 999, "sample_group_name": None}]
    )
    collector = collect(source, page_size=1)
    with pytest.raises(ValueError, match="owner"):
        collector.acquire()
    groups = [
        call
        for call in source.calls
        if urlsplit(call[0]).path.endswith("/tbl_sample_groups")
    ]
    assert len(groups) == 1
    assert "tbl_sites" in collector.tables


def test_duplicate_key_across_pages_refuses_before_next_request():
    source = Source(
        groups=[{"sample_group_id": 10, "site_id": 2, "sample_group_name": None}] * 2
    )
    collector = collect(source, page_size=1)
    with pytest.raises(ValueError, match="duplicate"):
        collector.acquire()
    assert (
        len(
            [
                call
                for call in source.calls
                if urlsplit(call[0]).path.endswith("/tbl_sample_groups")
            ]
        )
        == 2
    )


def test_empty_or_duplicate_selected_sites_refused_without_callback():
    source = Source()
