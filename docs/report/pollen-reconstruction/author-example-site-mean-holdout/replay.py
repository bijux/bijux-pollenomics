"""Rebuild and verify the author-example site-mean pollen holdout family."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

from bijux_pollenomics.reporting.presentation.report_portal.scientific_accounts import (
    load_routes,
    render_route,
    verified_authored_reader,
)

FAMILY = Path(__file__).resolve().parent
REPOSITORY = FAMILY.parents[3]
ARTIFACTS = REPOSITORY / "artifacts"
SOURCE_ROOTS = tuple(
    REPOSITORY / "packages" / name / "src"
    for name in (
        "bijux-pollenomics",
        "bijux-pollenomics-dev",
        "bijux-pollenomics-lra",
        "pollenomics",
    )
)
RUN = REPOSITORY / "docs/report/publication-replay/landclim-method-profile/reference"
BUFFERED_MANIFEST = (
    REPOSITORY
    / "docs/report/pollen-reconstruction/author-buffered-pollen/manifest.json"
)
REPORT_MANIFEST = REPOSITORY / "docs/report/pollen-reconstruction/manifest.json"
PRODUCER = (
    "packages/bijux-pollenomics-dev/src/bijux_pollenomics_dev/"
    "essd_reproduction/observed_pollen_baseline.py"
)
FILES = {"REPORT.md", "report.json", "scores.csv", "predictions.csv"}


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _check_inputs(source: Path) -> None:
    buffered = json.loads(BUFFERED_MANIFEST.read_text(encoding="utf-8"))
    source_manifest = source / "snapshot-manifest.json"
    if (
        not source_manifest.is_file()
        or _sha256(source_manifest) != buffered["private_source_manifest_sha256"]
    ):
        raise ValueError(
            "private source manifest identity differs from buffered pollen custody"
        )
    if not (source / "author").is_dir() or not (source / "reference").is_dir():
        raise ValueError("source root needs author/ and reference/")

    report = json.loads(REPORT_MANIFEST.read_text(encoding="utf-8"))
    entries = [item for item in report["files"] if item["path"] == PRODUCER]
    if len(entries) != 1 or _sha256(REPOSITORY / PRODUCER) != entries[0]["sha256"]:
        raise ValueError(
            "observed pollen producer differs from governed report manifest"
        )


def _render_report(output: Path) -> None:
    """Authenticate generated prose and publish its exact governed reader route."""
    relative = FAMILY.relative_to(REPOSITORY).as_posix() + "/REPORT.md"
    route = load_routes()[relative]
    retained = (FAMILY / "REPORT.md").read_bytes()
    verified_authored_reader(retained, route)
    path = output / "REPORT.md"
    if path.is_symlink() or not path.is_file():
        raise ValueError("generated reader must be a regular file")
    generated = path.read_bytes()
    verified_authored_reader(generated, route)
    rendered = render_route(generated, route)
    if rendered != retained:
        raise ValueError("generated reader differs from its governed route")
    path.write_bytes(rendered)


def _check_output(output: Path) -> None:
    actual = {item.name for item in output.iterdir()}
    if actual != FILES or any(
        (output / name).is_symlink() or not (output / name).is_file() for name in FILES
    ):
        raise ValueError(f"generated file set differs: {sorted(actual)}")
    differences = [
        name
        for name in sorted(FILES)
        if (output / name).read_bytes() != (FAMILY / name).read_bytes()
    ]
    if differences:
        raise ValueError(f"generated bytes differ from tracked family: {differences}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    source = args.source_root.resolve(strict=True)
    output = args.output.resolve()
    artifacts = ARTIFACTS.resolve()
    if output == artifacts or not output.is_relative_to(artifacts):
        parser.error("--output must be a directory beneath repository artifacts/")
    if output.exists() and (not output.is_dir() or any(output.iterdir())):
        parser.error(f"output must be absent or an empty directory: {output}")
    _check_inputs(source)

    output.mkdir(parents=True, exist_ok=True)
    producer_output = output / "producer"
    environment = os.environ.copy()
    environment.update(
        PYTHONDONTWRITEBYTECODE="1",
        PYTHONPATH=os.pathsep.join(str(path) for path in SOURCE_ROOTS),
        OMP_NUM_THREADS="1",
        OPENBLAS_NUM_THREADS="1",
        MKL_NUM_THREADS="1",
        VECLIB_MAXIMUM_THREADS="1",
        NUMEXPR_NUM_THREADS="1",
        BLIS_NUM_THREADS="1",
        RAYON_NUM_THREADS="1",
    )
    command = [
        sys.executable,
        "-m",
        "bijux_pollenomics_dev.essd_reproduction.observed_pollen_baseline",
        "--author",
        str(source / "author"),
        "--reference",
        str(source / "reference"),
        "--run",
        str(RUN),
        "--output",
        str(producer_output),
    ]
    print("+", " ".join(command), flush=True)
    subprocess.run(command, cwd=REPOSITORY, env=environment, check=True)

    actual = {item.name for item in producer_output.iterdir()}
    if actual != FILES or any(not (producer_output / name).is_file() for name in FILES):
        raise ValueError(f"producer file set differs: {sorted(actual)}")
    for name in ("scores.csv", "predictions.csv"):
        path = producer_output / name
        data = path.read_bytes()
        path.write_bytes(data.replace(b"\r\n", b"\n"))
    _render_report(producer_output)
    _check_output(producer_output)
    for name in sorted(FILES):
        (producer_output / name).rename(output / name)
    producer_output.rmdir()
    _check_output(output)
    print(f"verified {len(FILES)} tracked files in {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
