"""Replay the six source-owned SEAD report families against governed bytes."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import os
from pathlib import Path
import subprocess
import sys


@dataclass(frozen=True)
class Owner:
    name: str
    module: str
    source_argument: str
    files: tuple[str, ...]


OWNERS = (
    Owner(
        "analysis-integer-values",
        "sead_analysis_integer_values",
        "--data-root",
        ("report.json",),
    ),
    Owner(
        "analysis-numerical-values",
        "sead_analysis_numerical_values",
        "--data-root",
        ("report.json", "values.csv"),
    ),
    Owner(
        "chronology-country-accounting",
        "sead_chronology_country_accounting",
        "--repository",
        ("report.json", "rows.csv"),
    ),
    Owner(
        "country-coverage",
        "sead_country_coverage",
        "--repository",
        ("report.json", "rows.csv"),
    ),
    Owner(
        "source-unit-accounting",
        "sead_country_source_units",
        "--repository",
        ("report.json", "rows.csv"),
    ),
    Owner(
        "pollen-named-dataset-screen",
        "sead_pollen_screen",
        "--data-root",
        ("report.json", "sample-observations.csv"),
    ),
)


def compare(repository: Path, output: Path, owner: Owner) -> None:
    expected = set(owner.files)
    produced = {path.name for path in output.iterdir()}
    if produced != expected:
        raise ValueError(
            f"{owner.name}: generated files {sorted(produced)} != {sorted(expected)}"
        )
    governed = repository / "docs/report/source-relations/sead" / owner.name
    for name in owner.files:
        if (output / name).read_bytes() != (governed / name).read_bytes():
            raise ValueError(
                f"{owner.name}/{name}: generated bytes differ from governed report"
            )


def verify(repository: Path, output_root: Path, *, compare_existing: bool) -> None:
    repository = repository.resolve()
    output_root = output_root.resolve()
    if not output_root.is_relative_to(repository / "artifacts"):
        raise ValueError("SEAD replay output must be below repository artifacts")
    if compare_existing:
        if not output_root.is_dir():
            raise ValueError("SEAD replay output root does not exist")
    elif output_root.exists():
        raise ValueError("SEAD replay output root already exists")
    else:
        output_root.mkdir(parents=True)

    environment = dict(os.environ)
    environment.update(
        PYTHONDONTWRITEBYTECODE="1",
        OMP_NUM_THREADS="1",
        OPENBLAS_NUM_THREADS="1",
        MKL_NUM_THREADS="1",
        NUMEXPR_NUM_THREADS="1",
        VECLIB_MAXIMUM_THREADS="1",
    )
    for owner in OWNERS:
        output = output_root / owner.name
        if not compare_existing:
            source = repository / (
                "data" if owner.source_argument == "--data-root" else "."
            )
            subprocess.run(
                [
                    sys.executable,
                    "-m",
                    f"bijux_pollenomics_dev.source_completion.{owner.module}",
                    owner.source_argument,
                    str(source),
                    "--output",
                    str(output),
                ],
                cwd=repository,
                env=environment,
                check=True,
                timeout=600,
            )
        compare(repository, output, owner)
        print(f"{owner.name}: {len(owner.files)} governed files match", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", type=Path, default=Path.cwd())
    parser.add_argument("--output-root", required=True, type=Path)
    parser.add_argument("--compare-existing", action="store_true")
    args = parser.parse_args()
    verify(args.repository, args.output_root, compare_existing=args.compare_existing)


if __name__ == "__main__":
    main()
